__asm__(
"        .p2align 2\n"
"        .global zzrow_blit_keyed\n"
"        .type   zzrow_blit_keyed, %function\n"
"zzrow_blit_keyed:\n"
"        and     r3, r3, #255\n"         /* the scalar cmp must see a clean key */
"        vdup.8  q8, r3\n"
"        cmp     r2, #16\n"
"        blo     .Lbk_tail\n"
".Lbk_16:\n"
"        vld1.8  {d18, d19}, [r1]!\n"
"        vld1.8  {d20, d21}, [r0]\n"
"        vceq.i8 q11, q9, q8\n"          /* 0xFF where src == key */
"        vbit    q9, q10, q11\n"         /* keyed lanes take dst back */
"        vst1.8  {d18, d19}, [r0]!\n"
"        sub     r2, r2, #16\n"
"        cmp     r2, #16\n"
"        bhs     .Lbk_16\n"
".Lbk_tail:\n"
"        teq     r2, #0\n"
"        beq     .Lbk_done\n"
".Lbk_tl:\n"
"        ldrb    r12, [r1], #1\n"
"        cmp     r12, r3\n"
"        strbne  r12, [r0]\n"
"        add     r0, r0, #1\n"
"        subs    r2, r2, #1\n"
"        bne     .Lbk_tl\n"
".Lbk_done:\n"
"        bx      lr\n"
"        .size   zzrow_blit_keyed, . - zzrow_blit_keyed\n"
);

