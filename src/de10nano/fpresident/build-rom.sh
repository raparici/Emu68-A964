# Assembles fpresident.s into fpresident_rom.h.

set -e
here=$(cd "$(dirname "$0")" && pwd)
cd "$here"

VASM=${VASM:-vasmm68k_mot}
out=fpresident_rom.h
bin=/tmp/fpresident.bin

"$VASM" -Fbin -m68040 -opt-allbra ${VASMFLAGS:-} -o "$bin" fpresident.s
sz=$(wc -c < "$bin" | tr -d ' ')
echo "assembled $bin: $sz bytes"

# rotate-add checksum, matching bigmighd_board.c: sum = (sum<<1)+(sum>>31)+byte
sum=$(python3 - "$bin" <<'PY'
import sys
b=open(sys.argv[1],'rb').read()
s=0
for x in b:
    s=((s<<1)&0xffffffff)|(s>>31)
    s=(s+x)&0xffffffff
print("0x%08x" % s)
PY
)
echo "checksum $sum"

{
  echo "/* GENERATED by src/de10nano/fpresident/build-rom.sh — do not hand-edit."
  echo "   Source: fpresident.s ($sz bytes).  Regenerate after any change. */"
  xxd -i "$bin" | sed -e 's/unsigned char [A-Za-z0-9_]*\[\]/unsigned char fpresident_bin[]/' \
                      -e 's/unsigned int [A-Za-z0-9_]*_len/unsigned int fpresident_bin_len/'
  echo "#define FPRESIDENT_BIN_SUM ${sum}u"
} > "$out"
echo "wrote $out"
